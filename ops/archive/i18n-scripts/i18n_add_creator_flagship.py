def merge(lang: str, additions: dict) -> None:
    path = os.path.join(LOCALES_DIR, lang, "dashboardLayout.json")
    if not os.path.isfile(path):
        print(f"skip: {path} (missing)")
        return
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    added = 0
    for k, v in additions.items():
        if k not in data:
            data[k] = v
            added += 1
    # Sort alphabetically for a clean diff and consistency with existing file.
    data = dict(sorted(data.items()))
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{lang}: +{added} keys → {path}")

for lang, keys in KEYS_BY_LOCALE.items():
    merge(lang, keys)
