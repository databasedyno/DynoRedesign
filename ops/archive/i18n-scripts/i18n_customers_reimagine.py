for lang, new_keys in KEYS.items():
    path = f"/app/langs/locales/{lang}/common.json"
    data = json.load(open(path, encoding="utf-8"))
    cust = data.setdefault("customers", {})
    added = 0
    for k, v in new_keys.items():
        if cust.get(k) != v:
            cust[k] = v
            added += 1
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{lang}: {added} keys upserted, total customers keys = {len(cust)}")
