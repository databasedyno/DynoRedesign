const LANGS = ["en", "pt", "fr", "es", "de", "nl"];

function mergeFile(lang, file, adds) {
  const p = path.join(LOCALES, lang, file);
  const json = JSON.parse(fs.readFileSync(p, "utf8"));
  Object.assign(json, adds);
  fs.writeFileSync(p, JSON.stringify(json, null, 2) + "\n", "utf8");
  console.log(`  ✓ ${lang}/${file}`);
}

console.log("Merging dashboardLayout keys...");
for (const lang of LANGS) mergeFile(lang, "dashboardLayout.json", dash[lang]);

console.log("Merging companyDialog.createModal keys...");
for (const lang of LANGS) mergeFile(lang, "companyDialog.json", { createModal: createModal[lang] });

console.log("Done.");
