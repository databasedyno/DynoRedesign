def upsert(path: str, block: dict) -> int:
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    existing = data.get("twoFactor") or {}
    added = 0
    for k, v in block.items():
        if k not in existing:
            existing[k] = v
            added += 1
    data["twoFactor"] = existing
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    return added


def main():
    for lang in PROFILE:
        a = upsert(os.path.join(ROOT, lang, "profile.json"), PROFILE[lang])
        b = upsert(os.path.join(ROOT, lang, "auth.json"), AUTH[lang])
        print(f"{lang}: profile +{a}, auth +{b}")


if __name__ == "__main__":
    main()
