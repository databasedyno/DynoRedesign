def load(lang, ns):
    with open(os.path.join(ROOT, lang, f"{ns}.json"), encoding="utf-8") as f:
        return json.load(f)


def save(lang, ns, data):
    with open(os.path.join(ROOT, lang, f"{ns}.json"), "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")


def set_path(d, path, value):
    for k in path[:-1]:
        d = d.setdefault(k, {})
    d[path[-1]] = value


